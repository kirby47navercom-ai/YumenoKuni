"""Measure real glyph advances (em fraction) of every game font -> Game/Source/GlyphMetricsV4.hpp.

Per-glyph trial text (debate, panic, showdown) places one widget per glyph, so
spacing must come from the font, not one fixed step.
"""
import pathlib
from PIL import ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[1]
FONTS = ROOT / "Game/Assets/Fonts"
OUT = ROOT / "Game/Source/GlyphMetricsV4.hpp"
EXTRA = "…·「」『』！？～、。“”‘’―—"
SIZE = 1000


def main():
    rows = []
    for f in sorted(FONTS.rglob("*")):
        if f.suffix.lower() not in (".ttf", ".otf"):
            continue
        font = ImageFont.truetype(str(f), SIZE)
        adv = lambda ch: round(font.getlength(ch) / SIZE, 4)
        ascii_ = ",".join(f"{adv(chr(c))}f" for c in range(32, 127))
        extra = ",".join(f'{{"{ch}",{adv(ch)}f}}' for ch in EXTRA)
        rows.append(f' {{"{f.relative_to(FONTS).as_posix()}",{{{{{ascii_}}},{adv("가")}f,{{{extra}}}}}}},')
    OUT.write_text(
        "// Generated by tools/glyph_metrics.py from Game/Assets/Fonts. Do not edit.\n"
        "#pragma once\n#include <map>\n#include <string>\n#include <array>\n"
        "namespace glyphmetrics {\nstruct Font{std::array<float,95> ascii;float hangul;std::map<std::string,float> extra;};\n"
        "inline const std::map<std::string,Font>& all(){static const std::map<std::string,Font> m{\n"
        + "\n".join(rows) +
        "\n};return m;}\n"
        "// Advance in em of one UTF-8 glyph for a font path containing a key above.\n"
        "inline float advance(const std::string& g,const std::string& font){\n"
        " const Font* f=nullptr;for(const auto& [k,v]:all())if(font.find(k)!=std::string::npos){f=&v;break;}\n"
        " if(!f){auto it=all().find(\"pretendard/Pretendard-Medium.otf\");if(it==all().end())return .86f;f=&it->second;}\n"
        " unsigned char c=g.empty()?' ':g[0];if(c>=32&&c<127)return f->ascii[c-32];\n"
        " auto e=f->extra.find(g);if(e!=f->extra.end())return e->second;return f->hangul;\n}\n}\n",
        encoding="utf-8", newline="\n")
    print(len(rows), "fonts ->", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
