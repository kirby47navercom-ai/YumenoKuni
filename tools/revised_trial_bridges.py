def apply_trial_bridges(chapters, tasks):
    applied = set()
    for chapter in chapters.values():
        for node in chapter['nodes'].values():
            if node['type'] != 'task':
                continue
            task = tasks[node['taskId']]
            stage = task['stage']
            kind = stage['kind']
            ident = task['taskId']
            if kind == 'panic':
                opening, outcome = PANIC[ident]
                assert Counter(SPEAKERS[name] for name, _ in opening) == Counter(
                    lane['actor'] for lane in task['debate']['lanes']), ident
            elif kind == 'scrum':
                extra_them, extra_us, opening, outcome = SCRUM[ident]
                them = list(dict.fromkeys([row['themActor'] for row in stage['pairs']] +
                                          [SPEAKERS[name] for name in extra_them]))
                us = list(dict.fromkeys([row['usActor'] for row in stage['pairs']] +
                                        [SPEAKERS[name] for name in extra_us]))
                roster = chapter['trialRoster']
                assert Counter(them + us) == Counter(set(roster['seats']) - set(roster['dead'])), ident
                assert abs(len(them) - len(us)) <= 1 and 'mio' in us, ident
                stage['scrumSides'] = {'them': them, 'us': us}
            elif ident in HEARINGS:
                opening, outcome = HEARINGS[ident]
            elif ident in ADJACENT_TASKS:
                opening, outcome = [], ADJACENT_TASKS[ident]
                assert chapter['nodes'][node['next']]['type'] == 'task', ident
            else:
                continue
            queues = task.setdefault('queues', {})
            assert not queues.get('intro') and ident not in applied, ident
            applied.add(ident)
            if opening:
                lead = []
                for index, (who, text) in enumerate(opening, 1):
                    delivery = ''
                    if kind == 'panic' and index > 1:
                        delivery = 'interrupt'
                    elif kind in ('scrum', 'showdown', 'nonstop') and index == 1:
                        delivery = 'challenge'
                    line = _line(node, f'intro:{index}', who, text, delivery)
                    if kind == 'panic':
                        line['panicInterruption'] = True
                    lead.append(line)
                queues['intro'] = lead
            if outcome:
                queues.setdefault('success', []).append(_line(node, 'resolve', *outcome, 'resolve'))
    assert applied == PANIC.keys() | SCRUM.keys() | HEARINGS.keys() | ADJACENT_TASKS.keys()


def _line(node, suffix, speaker, text, delivery, **fields):
    return {'id': node['taskId'] + ':bridge:' + suffix, 'type': 'say', 'speaker': speaker,
            'actor': SPEAKERS[speaker], 'text': text, 'source': node['source'],
            **({'delivery': delivery} if delivery else {}), **fields}
