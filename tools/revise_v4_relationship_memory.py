def digest(t): return hashlib.sha256(t.encode()).hexdigest()

def apply():
    originals = {p: p.read_text(encoding='utf-8-sig') for p in SRC.glob('*.md')}
    texts = dict(originals)
    for prefix, old, new in EDITS:
        if old == new: continue
        paths = [p for p in texts if p.name.split('_')[0] == prefix and (prefix != '10' or '프롤로그' in p.name)]
        assert len(paths) == 1, prefix
        p = paths[0]
        assert old in texts[p], (prefix, old)
        texts[p] = texts[p].replace(old, new)
    revisions_path = ROOT/'tools/v4_editorial_revisions.json'
    revisions = json.loads(revisions_path.read_text(encoding='utf8'))
    existing = {(r['prefix'],r['location'],r['after']):r for r in revisions['revisions']}
    changed=[]
    for p, text in texts.items():
        if text == originals[p]:continue
        before = originals[p].splitlines();after = text.splitlines()
        assert len(before)==len(after),p
        prefix=p.name.split('_')[0]; location='root'
        for a,b in zip(before,after):
            m=re.match(r'^(#{1,6})\s+(.+)$',a)
            if m:
                token=re.match(r'^(?:선택\s+)?((?:[PTIRF]\d*[-:]|\d[-:])[A-Za-z0-9가-힣_-]+)',m[2])
                location=token[1] if token else 'h-'+digest(m[2])[:10]
            if a==b or not a.strip() or not a.startswith(('[','(','（')):continue
            # Original hash, even if the same line was previously copyedited.
            # A repeated reply may still use this alias elsewhere in the same
            # scene. Keep it when extending a revision to a new wording.
            previous=existing.get((prefix,location,a))
            row={'prefix':prefix,'location':location,'before':previous['before'] if previous else a.strip(),
                 'after':b.strip(),'reason':'2026-11-03 user-directed first encounter; participant relationship memories inaccessible until final chapter; present case facts and published IDs retained.'}
            if previous and 'authoredDelivery' in previous:row['authoredDelivery']=previous['authoredDelivery']
            if row['before'] != row['after']:
                revisions['revisions'].append(row)
        p.write_text(text,encoding='utf8')
        changed.append({'file':p.name,'before':digest(originals[p]),'after':digest(text)})
    unique={}
    for row in revisions['revisions']:
        key=(row['prefix'],row['location'],row['after'])
        if key in unique:assert unique[key]['before']==row['before'],key
        unique[key]=row
    revisions['revisions']=list(unique.values())
    revisions_path.write_text(json.dumps(revisions,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    # Reviewed ranges retain line counts and headings. Update exact hash locks,
    # not compiler routing or task judgments.
    for p in list((ROOT/'tools').glob('v4*.py'))+[ROOT/'tools/v4_story_route_sources.json']:
        t=p.read_text(encoding='utf-8-sig');new=t
        for row in changed:new=new.replace(row['before'],row['after'])
        if new!=t:p.write_text(new,encoding='utf8')
    receipt=AUDIT/'wording_changes.json'
    history=json.loads(receipt.read_text(encoding='utf8')) if receipt.exists() else []
    receipt.write_text(json.dumps(history+changed,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    print('Changed manuscripts:',len(changed))

if __name__=='__main__': apply()

