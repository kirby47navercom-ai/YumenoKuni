"""Author reproducible interruption bindings; never modifies testimony or answers."""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data/v4_story'


def grams(text):
    words = re.findall('[가-힣A-Za-z0-9]+', text)
    return {w[i:i+2] for w in words for i in range(len(w)-1)}

def build():
    tasks = json.loads((DATA/'native_tasks.json').read_text(encoding='utf-8'))['tasks']
    direction = json.loads((DATA/'trial_direction.json').read_text(encoding='utf-8'))
    followup = json.loads((ROOT/'data/presentation/nonstop_followup.json').read_text(encoding='utf-8'))['tasks']
    rows = []
    for tid, task in tasks.items():
        if task['stage']['kind'] != 'nonstop': continue
        main = [r for r in task['debate']['lines'] + direction['extra'].get(tid, []) if r.get('kind') != 'noise']
        noises = direction['noise'].get(tid, [])
        if not noises: continue
        assert len(noises) == len(main), (tid, len(main), len(noises))
        # One distinct response per utterance, including unmarked testimony.
        # Match topic/speaker only; answer type is not an allocation weight.
        assigned = {}
        def assign(n, visited):
            choices = sorted(range(len(main)), key=lambda i: len(grams(main[i]['text']) & grams(noises[n]['text'])), reverse=True)
            for i in choices:
                if i in visited or main[i]['actor'] == noises[n]['actor']: continue
                visited.add(i)
                if i not in assigned or assign(assigned[i], visited):
                    assigned[i] = n
                    return True
            return False
        for n in range(len(noises)): assert assign(n, set()), (tid, noises[n]['id'])
        assert len(assigned) == len(main)
        task_rows = []
        # Screen positions belong to the scene, never to a future weakpoint.
        placements = [(325,445,-14),(925,440,12),(350,190,-8),(920,195,9),(640,470,0)]
        for i, host in enumerate(main):
            noise = noises[assigned[i]]
            x,y,angle = placements[i % len(placements)]
            profile = direction['debate'][host['id']]['acting'].split('|')[1]
            multi_hit = '!' in noise['text'] and not (profile in ('qualify','reason') and len(noise['text']) <= 10)
            target = bool(host.get('weak') or host.get('agree') or host.get('kind')=='agree' or direction['debate'].get(host['id'],{}).get('decoy'))
            task_rows.append(dict(id=noise['id'],task=tid,text=noise['text'],actor=noise['actor'],host=host['id'],hostActor=host['actor'],hostText=host['text'],targetHost=target,angle=angle,x=x,y=y,delay=0,span=0,slot=0,minAction=1,hits=2 if int(tid[1])>=3 and multi_hit else 1,reason='Own utterance response; independent scene placement, no answer tracking'))
        # Extra responses are own authored lines. Multiple lines share the same
        # statement clock, and never consume more than the real 26 glyph slots.
        counts = {r['host']:1 for r in task_rows}
        sizes = {r['host']:len(r['text']) for r in task_rows}
        actors = list(dict.fromkeys(n['actor'] for n in noises))
        for n, text in enumerate(followup[tid]['extraNoise']):
            candidates = [h for h in main if counts[h['id']]<3 and sizes[h['id']]+len(text)<=26]
            def score(h):
                return len(grams(h['text']) & grams(text))*3 + (2 if n==1 and counts[h['id']]==2 else 0) - (2 if counts[h['id']]==3 else 0)
            assert candidates, tid
            host=max(candidates,key=score)
            slot=counts[host['id']];counts[host['id']]+=1;sizes[host['id']]+=len(text)
            actor=next(a for a in actors[n%len(actors):]+actors[:n%len(actors)] if a!=host['actor'])
            base=next(r for r in task_rows if r['host']==host['id'] and not r.get('extra'))
            x=(300,980)[slot-1];y=190 if base['y']>=330 else 510;angle=(-8,8)[slot-1]
            task_rows.append(dict(id=f'own:noise:{tid}:extra:{n}',task=tid,text=text,actor=actor,host=host['id'],hostActor=host['actor'],hostText=host['text'],targetHost=False,angle=angle,x=x,y=y,delay=0,span=0,slot=slot,minAction=1,hits=1,extra=True,reason='Own concurrent response; same statement lifetime'))
        rows.extend(task_rows)
    rows.sort(key=lambda r:r['id'])
    assert len({r['id'] for r in rows}) == len(rows)
    source = ROOT/'data/presentation/nonstop_noise_staging.json'
    source.write_text(json.dumps({'origin':'own-authored-reconstruction-not-original-DAT', 'rows':rows}, ensure_ascii=False, indent=1)+'\n', encoding='utf-8')
    header = '#pragma once\n// Generated by tools/build_nonstop_noise_staging.py. Source-only table; no DataGet path.\nnamespace debate {\nstruct NoiseBinding {const char *id,*host;float angle,delay,span;int slot,hits,minAction;float x,y;const char *task,*text,*actor;};\ninline constexpr NoiseBinding NOISE_BINDINGS[]{\n'
    for r in rows:
        header += '{'+json.dumps(r['id'])+','+json.dumps(r['host'])+f",{r['angle']:.2f}f,{r['delay']:.2f}f,{r['span']:.2f}f,{r['slot']},{r['hits']},{r['minAction']},{r['x']:.2f}f,{r['y']:.2f}f,"+json.dumps(r['task'])+','+json.dumps(r['text'] if r.get('extra') else '',ensure_ascii=False)+','+json.dumps(r['actor'])+'},\n'
    header += '};\n}\n'
    (ROOT/'Game/Source/NonstopNoiseRowsV4.hpp').write_text(header, encoding='utf-8')
    from build_nonstop_loop_hints import build as build_loop_hints
    build_loop_hints(followup)
    return rows

if __name__ == '__main__':
    rows = build()
    print(json.dumps({'rows':len(rows),'selfInterruptions':sum(r['actor']==r['hostActor'] for r in rows),'targetHosts':sum(r['targetHost'] for r in rows),'tasks':len({r['task'] for r in rows})}))
